-- FAMILY wave: family sharing, notifications (web push), daily summaries.

-- A robot shared with another account. The owner stays ai_device.user_id; an accepted row gives
-- `user_id` the role `member` or `co_owner` on the robot (see FamilyRole).
CREATE TABLE IF NOT EXISTS `ai_device_share` (
  `id`           bigint      NOT NULL COMMENT 'id',
  `device_id`    varchar(32) NOT NULL COMMENT 'ai_device.id',
  `owner_id`     bigint      NOT NULL COMMENT 'The robot owner when the invite was made',
  `user_id`      bigint      NOT NULL COMMENT 'The account the robot is shared with',
  `role`         varchar(16) NOT NULL DEFAULT 'member' COMMENT 'member | co_owner',
  `status`       varchar(16) NOT NULL DEFAULT 'pending' COMMENT 'pending | accepted | declined',
  `invited_by`   bigint      DEFAULT NULL COMMENT 'Who sent the invite',
  `responded_at` datetime    DEFAULT NULL COMMENT 'When it was accepted or declined',
  `create_date`  datetime    DEFAULT NULL,
  `update_date`  datetime    DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_share_device_user` (`device_id`, `user_id`),
  KEY `idx_share_user_status` (`user_id`, `status`)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COMMENT='Family sharing of robots';

-- One notification for one user.
CREATE TABLE IF NOT EXISTS `ai_notification` (
  `id`          bigint        NOT NULL COMMENT 'id',
  `user_id`     bigint        NOT NULL,
  `type`        varchar(32)   NOT NULL COMMENT 'robot_offline, alarm_missed, reminder_missed, care_*, daily_summary, family_*, test',
  `group_key`   varchar(16)   DEFAULT NULL COMMENT 'Preference group: offline, alarm, reminder, care, summary, family',
  `title_bn`    varchar(200)  DEFAULT NULL,
  `title_en`    varchar(200)  DEFAULT NULL,
  `body_bn`     varchar(1000) DEFAULT NULL,
  `body_en`     varchar(1000) DEFAULT NULL,
  `device_id`   varchar(32)   DEFAULT NULL,
  `robot_name`  varchar(64)   DEFAULT NULL,
  `dedupe_key`  varchar(128)  DEFAULT NULL COMMENT 'At most one notification per user and key',
  `read_at`     datetime      DEFAULT NULL,
  `create_date` datetime      DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_notification_user_date` (`user_id`, `create_date`),
  KEY `idx_notification_user_read` (`user_id`, `read_at`),
  KEY `idx_notification_user_dedupe` (`user_id`, `dedupe_key`)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COMMENT='Notifications';

-- Where a user's notifications are pushed: browser subscriptions (web, h5) and native tokens.
CREATE TABLE IF NOT EXISTS `ai_push_subscription` (
  `id`            bigint        NOT NULL COMMENT 'id',
  `user_id`       bigint        NOT NULL,
  `platform`      varchar(16)   NOT NULL COMMENT 'web | h5 | native',
  `endpoint`      varchar(1024) NOT NULL COMMENT 'Push service URL (web) or native token',
  `endpoint_hash` char(40)      NOT NULL COMMENT 'sha1(endpoint)',
  `p256dh`        varchar(255)  DEFAULT NULL COMMENT 'Browser key (web) or provider (native)',
  `auth`          varchar(64)   DEFAULT NULL,
  `fail_count`    int           DEFAULT 0,
  `last_ok`       datetime      DEFAULT NULL,
  `create_date`   datetime      DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_push_endpoint` (`endpoint_hash`),
  KEY `idx_push_user` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COMMENT='Push subscriptions';

-- Notification preferences per user (JSON, see NotifyPrefs).
CREATE TABLE IF NOT EXISTS `ai_notify_pref` (
  `user_id`     bigint   NOT NULL,
  `prefs`       text,
  `update_date` datetime DEFAULT NULL,
  PRIMARY KEY (`user_id`)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COMMENT='Notification preferences';

-- A robot's day: numbers (JSON) and a short Bangla and English text.
CREATE TABLE IF NOT EXISTS `ai_daily_summary` (
  `id`          bigint        NOT NULL COMMENT 'id',
  `device_id`   varchar(32)   NOT NULL,
  `day`         varchar(10)   NOT NULL COMMENT 'YYYY-MM-DD, Asia/Dhaka',
  `data`        text          COMMENT 'talkCount, focusMinutes, games, reminders, memories, mood, bond',
  `text_bn`     varchar(1000) DEFAULT NULL,
  `text_en`     varchar(1000) DEFAULT NULL,
  `final_flag`  tinyint       DEFAULT 0 COMMENT '1: built after the day ended',
  `create_date` datetime      DEFAULT NULL,
  `update_date` datetime      DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_summary_device_day` (`device_id`, `day`)
) ENGINE=InnoDB DEFAULT CHARACTER SET utf8mb4 COMMENT='Daily robot summaries';

-- Who the push services see as the sender (VAPID "sub"): a mailto: or https: URL of the operator.
-- The VAPID key pair itself (push.vapid_public_key, push.vapid_private_key) is generated by
-- manager-api at the first start and stored as hidden params (param_type 0).
INSERT INTO `sys_params` (`id`, `param_code`, `param_value`, `value_type`, `param_type`, `remark`)
SELECT 2026110301, 'push.vapid_subject', 'null', 'string', 1, 'Web push sender contact (VAPID sub), e.g. mailto:support@your-domain. null: mailto:admin@localhost'
WHERE NOT EXISTS (SELECT 1 FROM `sys_params` WHERE `param_code` = 'push.vapid_subject')
  AND NOT EXISTS (SELECT 1 FROM `sys_params` WHERE `id` = 2026110301);

-- Product features: family sharing for every product; care alerts and the daily summary for
-- TinyBot (they read its companion data).
UPDATE `ai_product` SET `features` = JSON_ARRAY_APPEND(`features`, '$', 'family')
WHERE `product_key` IN ('tinybot', 'generic') AND JSON_VALID(`features`) AND NOT JSON_CONTAINS(`features`, '"family"');
UPDATE `ai_product` SET `features` = JSON_ARRAY_APPEND(`features`, '$', 'care')
WHERE `product_key` = 'tinybot' AND JSON_VALID(`features`) AND NOT JSON_CONTAINS(`features`, '"care"');
UPDATE `ai_product` SET `features` = JSON_ARRAY_APPEND(`features`, '$', 'summary')
WHERE `product_key` = 'tinybot' AND JSON_VALID(`features`) AND NOT JSON_CONTAINS(`features`, '"summary"');
