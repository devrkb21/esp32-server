// Turns Nobix's legal texts (docs/legal/{terms,privacy}.{bn,en}.md, written by the owner's side)
// into src/views/legal/texts.js, structured data the legal page renders. Run `npm run legal`
// after the Markdown changes and commit both. The text is copied as written: nothing is reworded.
//
// The Markdown it understands is the small subset the documents use:
//   # Title
//   Effective date: ...          (the first paragraph after the title, "কার্যকর তারিখ: ..." in Bangla)
//   ## Section heading
//   a paragraph (lines joined), optionally opening with a bold lead-in: **Lead.** rest
//   - list item, optionally opening with a bold lead-in
// Anything else (inline bold mid-sentence, links, code, nested lists) stops the script so a new
// construct is never dropped silently.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const docs = resolve(here, '../../../docs/legal');
const out = resolve(here, '../src/views/legal/texts.js');

const DOCS = ['terms', 'privacy'];
const LANGS = ['bn', 'en'];
const EFFECTIVE = /^(Effective date|কার্যকর তারিখ):/;

function inline(raw, where) {
  const s = raw.trim();
  const m = s.match(/^\*\*(.+?)\*\*\s*(.*)$/);
  const node = m ? { lead: m[1], text: m[2] } : { text: s };
  const rest = `${node.lead || ''} ${node.text}`;
  if (/\*\*|__|`|\[[^\]]*\]\(|<[a-z]/i.test(rest)) throw new Error(`${where}: unsupported inline Markdown in "${s}"`);
  return node;
}

export function parse(md, where = 'doc') {
  const lines = md.replace(/\r\n?/g, '\n').split('\n');
  const doc = { title: '', effective: '', intro: [], sections: [] };
  let blocks = doc.intro;
  let para = null;
  let list = null;
  const endPara = () => { if (para) { blocks.push({ type: 'p', ...inline(para.join(' '), where) }); para = null; } };
  const endList = () => { if (list) { blocks.push({ type: 'list', items: list }); list = null; } };

  lines.forEach((line, i) => {
    const at = `${where}:${i + 1}`;
    if (!line.trim()) { endPara(); endList(); return; }
    let m;
    if ((m = line.match(/^# (.+)$/))) {
      endPara(); endList();
      if (doc.title) throw new Error(`${at}: a second title`);
      doc.title = m[1].trim();
    } else if ((m = line.match(/^## (.+)$/))) {
      endPara(); endList();
      const section = { heading: m[1].trim(), blocks: [] };
      doc.sections.push(section);
      blocks = section.blocks;
    } else if ((m = line.match(/^- (.+)$/))) {
      endPara();
      list = list || [];
      list.push(inline(m[1], at));
    } else if (/^(#{3,}|\s+-|\d+\.\s|>|\|)/.test(line)) {
      throw new Error(`${at}: unsupported Markdown "${line}"`);
    } else {
      endList();
      para = para || [];
      para.push(line.trim());
    }
  });
  endPara(); endList();

  const first = doc.intro[0];
  if (first && first.type === 'p' && !first.lead && EFFECTIVE.test(first.text)) {
    doc.effective = first.text;
    doc.intro.shift();
  }
  if (!doc.title || !doc.effective || !doc.sections.length) throw new Error(`${where}: title, effective line or sections missing`);
  return doc;
}

function build() {
  const data = {};
  for (const name of DOCS) {
    data[name] = {};
    for (const lang of LANGS) {
      const file = resolve(docs, `${name}.${lang}.md`);
      data[name][lang] = parse(readFileSync(file, 'utf8'), `${name}.${lang}.md`);
    }
  }
  return data;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const data = build();
  const body = [
    '// GENERATED by scripts/legal-gen.mjs from docs/legal/*.md. Do not edit by hand: change the',
    '// Markdown and run `npm run legal`. Nobix\'s terms of use and privacy policy, Bangla and English.',
    '// "{{CONTACT}}" is filled in at render time from LEGAL_CONTACT (src/views/legal/legal.js).',
    `export const LEGAL_TEXTS = ${JSON.stringify(data, null, 2)};`,
    '',
    'export default LEGAL_TEXTS;',
    '',
  ].join('\n');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, body, 'utf8');
  console.log(`legal-gen: wrote ${out}`);
}
